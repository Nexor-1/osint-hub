def _svg(name: str, color: str, stroke: float) -> bytes:
    body = PATHS.get(name) or PATHS["info"]
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">'
        f'{body.replace("currentColor", color)}</svg>'
    ).encode()


def _dpr() -> float:
    app = QGuiApplication.instance()
    screen = app.primaryScreen() if app else None
    return max(1.0, screen.devicePixelRatio() if screen else 1.0)


@lru_cache(maxsize=1024)
def pixmap(name: str, color: str = theme.SUB, size: int = 18, stroke: float = 1.6) -> QPixmap:
    """Render icon ``name`` stroked with ``color`` at ``size`` logical pixels."""
    return render_svg(_svg(name, color, stroke), size, size)


def render_svg(data: bytes | str, width: int, height: int) -> QPixmap:
    if isinstance(data, str):
        data = data.encode()
    dpr = _dpr()
    pm = QPixmap(int(width * dpr), int(height * dpr))
    pm.fill(Qt.GlobalColor.transparent)
    renderer = QSvgRenderer(QByteArray(data))
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(p, QRectF(0, 0, pm.width(), pm.height()))
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm


@lru_cache(maxsize=512)
def icon(name: str, color: str = theme.SUB, size: int = 18, active_color: str | None = None) -> QIcon:
    """QIcon with an optional different colour for the checked/active state."""
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size), QIcon.Mode.Normal, QIcon.State.Off)
    ic.addPixmap(pixmap(name, theme.DISABLED, size), QIcon.Mode.Disabled, QIcon.State.Off)
    if active_color:
        ic.addPixmap(pixmap(name, active_color, size), QIcon.Mode.Normal, QIcon.State.On)
        ic.addPixmap(pixmap(name, active_color, size), QIcon.Mode.Active, QIcon.State.Off)
    return ic


def qsize(n: int) -> QSize:
    return QSize(n, n)
